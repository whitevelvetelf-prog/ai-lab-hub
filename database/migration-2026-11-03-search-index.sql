SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS search_index (
    id         INT UNSIGNED     NOT NULL AUTO_INCREMENT,
    product_id INT UNSIGNED     NOT NULL,
    lang       VARCHAR(5)       NOT NULL DEFAULT '',
    field_type VARCHAR(16)      NOT NULL DEFAULT '',
    token      VARCHAR(64)      NOT NULL DEFAULT '',
    weight     TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_search_token (token, product_id, field_type, weight),
    KEY idx_search_product (product_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS search_index_state (
    product_id   INT UNSIGNED NOT NULL,
    content_hash CHAR(32)     NOT NULL,
    indexed_at   DATETIME     NOT NULL,
    PRIMARY KEY (product_id)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS search_synonyms (
    id         INT UNSIGNED NOT NULL AUTO_INCREMENT,
    group_id   INT UNSIGNED NOT NULL,
    word       VARCHAR(100) NOT NULL,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_search_synonym (group_id, word),
    KEY idx_search_synonym_word (word)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS search_log (
    id            INT UNSIGNED      NOT NULL AUTO_INCREMENT,
    query         VARCHAR(200)      NOT NULL,
    lang          VARCHAR(5)        NOT NULL DEFAULT 'uk',
    results_count SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    created_at    DATETIME          NOT NULL,
    PRIMARY KEY (id),
    KEY idx_search_log_created (created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

