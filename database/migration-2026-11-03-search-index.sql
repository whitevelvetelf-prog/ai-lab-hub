--   ui_translations     — EN-написи пошуку (українські — app/translations.php).
--
-- Лише CREATE TABLE IF NOT EXISTS (індекси — у самих CREATE TABLE) та INSERT IGNORE.
-- Жодних DROP / ALTER / TRUNCATE / DELETE / FOREIGN KEY. Повторний запуск безпечний.
-- Після імпорту: CRM → «Пошук» → «Перебудувати пошуковий індекс» (або індекс наповниться сам під час пошуку).
