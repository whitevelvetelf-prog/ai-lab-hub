function promo_tr(string $key, mixed ...$args): string
{
    $pair = PROMO_I18N[$key] ?? null;
    if ($pair === null) {
        return $key;
    }
    $txt = promo_lang() === 'en' ? $pair[1] : $pair[0];

    return $args === [] ? $txt : vsprintf($txt, $args);
}

/** @param list<string> $keys @return array<string,string> */
function promo_tr_many(array $keys, ?string $lang = null): array
{
    $out = [];
    foreach ($keys as $k) {
        $out[$k] = promo_tr($k);
    }

    return $out;
}
