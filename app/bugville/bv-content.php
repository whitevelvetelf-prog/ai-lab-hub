/** 1.1 «Скільки монет?» (bug): автомат видав неправильну решту; гравець вводить правильну. */
function bv_gen_change_due(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $price = $rng->int(5, 99);
    $paid = $rng->pick(array_values(array_filter([10, 20, 50, 100, 200], static fn($n) => $n > $price)));
    $due = $paid - $price;
    $kinds = ['less', 'more'];
    if ($due >= 10 && $due < 100 && intdiv($due, 10) !== $due % 10 && $due % 10 !== 0) {
        $kinds[] = 'swap';
    }
    $kind = $rng->pick($kinds);
    if ($kind === 'less' && $due < 10) {
        $kind = 'more';
    }
    $shown = match ($kind) {
        'less' => $due - 10,
        'more' => $due + 10,
        default => (int) (($due % 10) . intdiv($due, 10)),
    };
    $name = $rng->pick(BV_NAMES);
    $good = $rng->pick(BV_GOODS);
    $place = $rng->pick(BV_PLACES);
    $what = match ($kind) {
        'less' => 'Автомат видав на 10 грн менше — це поломка.',
        'more' => 'Автомат видав зайві 10 грн — це теж поломка.',
        default => 'Автомат переставив цифри місцями — це поломка.',
    };

    return ['params' => compact('price', 'paid', 'due', 'shown', 'kind'),
        'payload' => ['text' => "Автомат {$place}. {$name} купує «{$good}» за {$price} грн і вкидає {$paid} грн. Автомат видає решту: {$shown} грн.",
            'question' => 'Скільки решти мав видати автомат? Введіть число.', 'input' => 'number'],
        'answer' => ['type' => 'number', 'value' => $due, 'tolerance' => 0],
        'explain' => ['text' => "{$paid} − {$price} = {$due}. {$what}"],
        'hint' => ['text' => 'Відніміть ціну від суми, яку вкинули.']];
}

