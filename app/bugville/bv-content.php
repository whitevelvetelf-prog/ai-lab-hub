    $lim = $rng->int(12, 18);   // вище 18 замало довгих імен для різних варіантів
    $pool = [];
    foreach ($parts as $a) {
        $pool[] = $a;
        foreach ($parts as $b) {
            if ($a !== $b) {
                $pool[] = "{$a}-{$b}";
            }
        }
    }
    $pool = $rng->shuffle($pool);
    $len = static fn(string $s) => mb_strlen($s);
    $short = array_values(array_filter($pool, static fn($s) => $len($s) <= $lim));
    $long = array_values(array_filter($pool, static fn($s) => $len($s) > $lim + 1 && $len($s) <= $lim + 12));
    $ok1 = $short[0];
    $ok2 = current(array_filter($short, static fn($s) => $len($s) !== $len($ok1) && $len($s) >= $lim - 4)) ?: $short[1];
    $rejected = $long[0];
    $bug = current(array_filter($long, static fn($s) => $len($s) !== $len($rejected))) ?: $long[1];
    $rows = [['text' => "{$ok1} (" . $len($ok1) . ') → прийнято'], ['text' => "{$ok2} (" . $len($ok2) . ') → прийнято'],
        ['text' => "{$rejected} (" . $len($rejected) . ') → «Задовге»'], ['bug' => true, 'text' => "{$bug} (" . $len($bug) . ') → прийнято']];

    return bv_pack(['limit' => $lim], "Правило форми: «Імʼя — не довше {$lim} символів». У дужках — скільки символів у імені.",
        'Який рядок показує поломку?', $rows, $rng,
        $len($bug) . " більше за {$lim} — імʼя не вміститься на бирці, а форма його прийняла. Рядок «{$rejected}» форма відхилила правильно.",
        "Порівняйте число в дужках із межею {$lim}.");
}

// ---------- Рівень 3 «Бібліотека» -------------------------------------------------------------------------------

function bv_ddmm(int $day, int $month): string
{
    return sprintf('%02d.%02d', $day, $month);
}

/** Звичайна видача: [день, місяць видачі, день, місяць повернення] через 14 днів. */
function bv_loan(BvRng $rng, int $month): array
{
    $day = $rng->int(1, 14);
    $ret = mktime(0, 0, 0, $month, $day + 14, 2026);

    return [$day, $month, (int) date('j', $ret), (int) date('n', $ret)];
}

/** 3.1 «Не та дата» (expected): неможлива дата або повернення раніше за видачу. */
function bv_gen_bad_date(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $books = array_slice($rng->shuffle(BV_BOOKS), 0, 4);
    $readers = array_slice($rng->shuffle(BV_NAMES), 0, 4);
    $month = $rng->int(2, 10);
    $rows = [];
    foreach ([0, 1, 2] as $i) {
        [$d1, $m1, $d2, $m2] = bv_loan($rng, $month);
        $rows[] = ['text' => "«{$books[$i]}» · {$readers[$i]} · видано " . bv_ddmm($d1, $m1) . ' · повернути ' . bv_ddmm($d2, $m2)];
    }
    if ($rng->int(0, 1) === 0) {
        [$dd, $mm, $days] = $rng->pick([[31, 4, 30], [31, 6, 30], [30, 2, 28], [31, 9, 30], [31, 11, 30]]);
        $issued = bv_ddmm($dd - 14, $mm);
        $rows[] = ['bug' => true, 'text' => "«{$books[3]}» · {$readers[3]} · видано {$issued} · повернути " . bv_ddmm($dd, $mm)];
        $monthName = [2 => 'лютому', 4 => 'квітні', 6 => 'червні', 9 => 'вересні', 11 => 'листопаді'][$mm];
        $explain = "У {$monthName} {$days} днів, тож " . bv_ddmm($dd, $mm) . ' не буває. Очікували справжню дату — отримали неможливу.';
    } else {
        $d1 = $rng->int(15, 27);
        $rows[] = ['bug' => true, 'text' => "«{$books[3]}» · {$readers[3]} · видано " . bv_ddmm($d1, $month) . ' · повернути ' . bv_ddmm($d1 - $rng->int(5, 13), $month)];
        $explain = 'Повернути книжку раніше, ніж її видали, не можна. Очікувано: дата повернення після дати видачі.';
    }

    return bv_pack(['month' => $month], 'Таблиця видачі книжок: назва · читач · видано · повернути (книжку дають на 14 днів).',
        'Який рядок показує поломку?', $rows, $rng, $explain, 'Перевірте, чи кожна дата можлива і чи повернення пізніше за видачу.');
}

/** 3.2 «Двійник» (actual): один рядок записано двічі; гравець вибирає книжку. */
function bv_gen_duplicate_row(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $books = array_slice($rng->shuffle(BV_BOOKS), 0, 5);
    $nums = bv_distinct($rng, 100, 399, 5);
    $readers = array_slice($rng->shuffle(BV_NAMES), 0, 5);
    $dupIdx = $rng->int(0, 4);
    $month = $rng->int(1, 12);
    $items = [];
    foreach ($books as $i => $b) {
        $items[] = ['text' => "«{$b}» · інв. № {$nums[$i]} · {$readers[$i]} · " . bv_ddmm($rng->int(1, 28), $month)];
    }
    $dup = $items[$dupIdx];
    $insertAt = ($dupIdx + $rng->int(2, 4)) % 6;
    array_splice($items, $insertAt, 0, [$dup]);
    $rows = array_map(static fn($i) => ['text' => "«{$books[$i]}»", 'bug' => $i === $dupIdx], range(0, 4));
    $v = bv_pack(['dup' => $dupIdx], 'На полиці 5 книжок, а в таблиці 6 рядків.', 'Яка книжка записана двічі?', $rows, $rng,
        "Фактично книжок 5, а рядків 6: «{$books[$dupIdx]}» з інв. № {$nums[$dupIdx]} записана двічі. Один номер — одна книжка.",
        'Порівняйте інвентарні номери.');
    $v['payload']['items'] = $items;

    return $v;
}

/** 3.3 «Порожня клітинка» (missing): у рядку бракує даних. */
function bv_gen_empty_cell(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $books = array_slice($rng->shuffle(BV_BOOKS), 0, 4);
    $readers = array_slice($rng->shuffle(BV_NAMES), 0, 4);
    $month = $rng->int(2, 10);
    $col = $rng->pick(['reader', 'return', 'issued']);
    $rows = [];
    foreach ($books as $i => $b) {
        [$d1, $m1, $d2, $m2] = bv_loan($rng, $month);
        $cells = ['book' => "«{$b}»", 'reader' => $readers[$i], 'issued' => bv_ddmm($d1, $m1), 'return' => bv_ddmm($d2, $m2)];
        $isBug = $i === 3;
        if ($isBug) {
            $cells[$col] = '(порожньо)';
        }
        $rows[] = ['text' => implode(' · ', $cells), 'bug' => $isBug];
    }
    $explain = match ($col) {
        'reader' => 'Книжку видали, але не записали кому. Бракує даних — її не знайдуть.',
        'return' => 'Без дати повернення ніхто не нагадає про книжку.',
        default => 'Невідомо, коли книжку видали, — не порахувати, чи вона вже прострочена.',
    };

    return bv_pack(['col' => $col], 'Таблиця видачі книжок: назва · читач · видано · повернути.', 'Який рядок показує поломку?', $rows, $rng,
        $explain, 'Шукайте клітинку, в якій нічого немає.');
}

/** 3.4 «Переплутані стовпці» (mismatch): два значення в рядку стоять не у своїх стовпцях. */
function bv_gen_swapped_columns(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $books = array_slice($rng->shuffle(BV_BOOKS), 0, 4);
    if ($rng->int(0, 1) === 0) {
        $authors = [];
        foreach ($books as $i => $b) {
            $authors[] = $rng->pick(BV_AUTHORS);
        }
        $years = bv_distinct($rng, 1995, 2025, 4);
        $rows = [];
        foreach ($books as $i => $b) {
            $rows[] = $i === 3 ? ['bug' => true, 'text' => "«{$b}» · {$years[$i]} · {$authors[$i]}"] : ['text' => "«{$b}» · {$authors[$i]} · {$years[$i]}"];
        }

        return bv_pack(['kind' => 'author_year'], 'Каталог, стовпці: Назва · Автор · Рік.', 'Який рядок показує поломку?', $rows, $rng,
            'У стовпці «Автор» стоїть рік, а в «Рік» — імʼя. Значення не відповідають своїм стовпцям.', 'Перевірте, що в кожному стовпці стоїть своє.');
    }
    $readers = array_slice($rng->shuffle(BV_NAMES), 0, 4);
    $month = $rng->int(1, 12);
    $rows = [];
    foreach ($books as $i => $b) {
        $d = bv_ddmm($rng->int(1, 28), $month);
        $rows[] = $i === 3 ? ['bug' => true, 'text' => "«{$b}» · {$d} · {$readers[$i]}"] : ['text' => "«{$b}» · {$readers[$i]} · {$d}"];
    }

    return bv_pack(['kind' => 'reader_date'], 'Таблиця, стовпці: Книжка · Читач · Видано.', 'Який рядок показує поломку?', $rows, $rng,
        'Дата опинилася в «Читач», а імʼя — у «Видано». Значення не відповідають своїм стовпцям.', 'Перевірте, що в кожному стовпці стоїть своє.');
}

