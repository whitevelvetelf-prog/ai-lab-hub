/** 2.3 «Літери замість цифр» (invalid): у телефоні літера, схожа на цифру. */
function bv_gen_phone_digits(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    $op = static fn() => $rng->pick(['50', '63', '66', '67', '68', '73', '93', '97', '98']);
    $num = static fn() => $rng->int(100, 999) . ' ' . $rng->int(10, 99) . ' ' . $rng->int(10, 99);
    $look = [['O', '0', 'велика літера O схожа на нуль'], ['l', '1', 'мала літера l схожа на одиницю'], ['З', '3', 'українська літера З схожа на трійку'],
        ['б', '6', 'літера б схожа на шістку'], ['I', '1', 'велика літера I схожа на одиницю']];
    [$letter, $digit, $why] = $rng->pick($look);
    // Літера-двійник стає на місце цифри в абонентській частині (код оператора лишається справжнім).
    $sub = str_split($num());
    $digitPos = array_keys(array_filter($sub, static fn($c) => ctype_digit($c)));
    $sub[$digitPos[$rng->int(0, count($digitPos) - 1)]] = $letter;
    $badNum = $op() . ' ' . implode('', $sub);
    $rows = [['text' => '+380 ' . $op() . ' ' . $num() . ' → прийнято'], ['text' => '+380 ' . $op() . ' ' . $num() . ' → прийнято'],
        ['text' => $rng->pick(['+380 ' . $op() . ' → відхилено', '123 → відхилено', '+380 ' . $op() . ' ABC 12 34 → відхилено'])],
        ['bug' => true, 'text' => "+380 {$badNum} → прийнято"]];

    return bv_pack(['letter' => $letter], 'Журнал телефонів для SMS про посилку:', 'Який рядок показує поломку?', $rows, $rng,
        "У номері телефону лише цифри. У «+380 {$badNum}» {$why}, тож SMS на такий номер не прийде, а форма його прийняла.",
        'Уважно подивіться на кожен символ прийнятих номерів.');
}

