/**
 * Рядки → варіанти відповіді: перемішує, дає id o1…, повертає [options, correct id, текст поломки].
 * @param list<array{text:string, bug?:bool}> $rows рівно один із bug = true
 */
function bv_rows(BvRng $rng, array $rows, bool $shuffle = true): array
{
    $options = [];
    $correct = '';
    $bugText = '';
    foreach ($shuffle ? $rng->shuffle($rows) : array_values($rows) as $i => $r) {
        $id = 'o' . ($i + 1);
        $options[] = ['id' => $id, 'text' => $r['text']];
        if (!empty($r['bug'])) {
            $correct = $id;
            $bugText = $r['text'];
        }
    }

    return [$options, $correct, $bugText];
}

/** Готовий варіант з рядків (single). */
function bv_pack(array $params, string $text, string $question, array $rows, BvRng $rng, string $explain, string $hint, array $extra = [],
    bool $shuffle = true): array
{
    [$options, $correct] = bv_rows($rng, $rows, $shuffle);

    return ['params' => $params, 'payload' => ['text' => $text, 'question' => $question, 'options' => $options] + $extra,
        'answer' => ['type' => 'single', 'correct' => $correct], 'explain' => ['text' => $explain], 'hint' => ['text' => $hint]];
}

/** Кілька різних чисел із діапазону. @return list<int> */
function bv_distinct(BvRng $rng, int $min, int $max, int $count, array $avoid = []): array
{
    $out = [];
    $guard = 0;
    while (count($out) < $count && $guard++ < 200) {
        $v = $rng->int($min, $max);
        if (!in_array($v, $out, true) && !in_array($v, $avoid, true)) {
            $out[] = $v;
        }
    }

    return $out;
}

