/** 2.1 «Порожнє поле» (required): обовʼязкове поле порожнє, а форма пішла далі. */
function bv_gen_required_field(PDO $pdo, BvRng $rng, array $p, string $lang): array
{
    [$name, $latin] = $rng->pick([['Олег', 'oleh'], ['Марта', 'marta'], ['Ліна', 'lina'], ['Ірина', 'iryna'], ['Тарас', 'taras'],
        ['Софія', 'sofiia'], ['Іван', 'ivan'], ['Дана', 'dana'], ['Петро', 'petro'], ['Оксана', 'oksana']]);
    $sur = $rng->pick(BV_SURNAMES);
    $mail = $latin . '@poshta.bv';
    $forms = [
        ['title' => 'Посилка', 'done' => 'Посилку відправлено', 'fields' => [['Отримувач', true, "{$name} {$sur}"],
            ['Телефон', true, '+380 67 ' . $rng->int(100, 999) . ' ' . $rng->int(10, 99) . ' ' . $rng->int(10, 99)],
            ['Місто', true, $rng->pick(BV_CITIES)], ['Відділення', true, '№ ' . $rng->int(1, 120)], ['Примітка', false, 'Обережно, скло']]],
        ['title' => 'Відправник', 'done' => 'Заявку прийнято', 'fields' => [['Імʼя', true, $name], ['Email', true, $mail],
            ['Адреса', true, 'вул. Липова, ' . $rng->int(1, 80)], ['Місто', true, $rng->pick(BV_CITIES)], ['Примітка', false, 'Дзвонити після 18:00']]],
        ['title' => 'Підписка на газету', 'done' => 'Підписку оформлено', 'fields' => [['Прізвище', true, $sur], ['Місто', true, $rng->pick(BV_CITIES)],
            ['Індекс', true, (string) $rng->int(10000, 99999)], ['Місяців', true, (string) $rng->int(1, 12)], ['Побажання', false, 'Без реклами']]],
    ];
    $f = $rng->pick($forms);
    $required = array_values(array_filter($f['fields'], static fn($x) => $x[1]));
    $empty = $rng->pick($required)[0];
    $optEmpty = $rng->int(0, 1) === 1;
    $rows = [];
    foreach ($f['fields'] as [$label, $req, $value]) {
        $isBug = $label === $empty;
        $val = $isBug || (!$req && $optEmpty) ? '(порожньо)' : $value;
        $rows[] = ['text' => $label . ($req ? '*' : '') . ': ' . $val, 'bug' => $isBug];
    }
    $explain = "Поле «{$empty}*» обовʼязкове, а лишилося порожнім — форма мала попросити його заповнити, а не писати «{$f['done']}»."
        . ($optEmpty ? ' Порожнє необовʼязкове поле без зірочки — це нормально.' : '');

    // Поля форми йдуть у звичному порядку (keep_order): перемішаний бланк виглядав би дивно.
    return bv_pack(['form' => $f['title'], 'empty' => $empty], "Форма «{$f['title']}», внизу напис «{$f['done']}». Зірочкою * позначені обовʼязкові поля.",
        'Через яке поле форма не мала піти далі?', $rows, $rng, $explain, 'Шукайте поле із зірочкою, у якому нічого немає.', ['keep_order' => true], false);
}

